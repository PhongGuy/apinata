#!/usr/bin/env bash
# Rebuild the QuickJS-ready bundles from the exact versions in package-lock.json.
# Output is CommonJS: the host evaluates it inside (function(module, exports){...}).
# Each vendor file is a fixed licence header followed by the unmodified esbuild output.
set -euo pipefail
cd "$(dirname "$0")"
npm ci --no-audit --no-fund --user-agent apinata-research >/dev/null
mkdir -p dist
for name in buffer ajv; do
  npx --no-install esbuild "src/$name.js" \
    --bundle --format=cjs --platform=neutral --main-fields=main,module \
    --target=es2020 --minify --legal-comments=none --charset=utf8 \
    --outfile="dist/$name.cjs.js"
done

vendor=../../crates/apinata-core/src/script/vendor
{
  cat <<'EOF'
/*!
 * buffer 5.7.1 (MIT, licenses/buffer-MIT.txt), with base64-js 1.5.1 (MIT,
 * licenses/base64-js-MIT.txt) and ieee754 1.2.1 (BSD-3-Clause, licenses/ieee754-BSD-3-Clause.txt).
 * Bundled with esbuild 0.28.2; generated by tools/script-bundles/build.sh; do not edit.
 */
EOF
  cat dist/buffer.cjs.js
} >"$vendor/buffer-5.7.1.min.js"
{
  cat <<'EOF'
/*!
 * ajv 8.20.0 (MIT, licenses/ajv-MIT.txt) and ajv-formats 2.1.1 (MIT, licenses/ajv-formats-MIT.txt),
 * with fast-deep-equal 3.1.3 (MIT, licenses/fast-deep-equal-MIT.txt), fast-uri 3.1.9
 * (BSD-3-Clause, licenses/fast-uri-BSD-3-Clause.txt) and json-schema-traverse 1.0.0 (MIT,
 * licenses/json-schema-traverse-MIT.txt).
 * Bundled with esbuild 0.28.2; generated by tools/script-bundles/build.sh; do not edit.
 */
EOF
  cat dist/ajv.cjs.js
} >"$vendor/ajv-8.20.0.min.js"
