#!/usr/bin/env bash
# Rebuild the QuickJS-ready bundles from the exact versions in package-lock.json.
# Output is CommonJS: the host evaluates it inside (function(module, exports){...}).
# Each vendor file is a fixed licence header followed by the unmodified esbuild output.
set -euo pipefail
cd "$(dirname "$0")"
npm ci --no-audit --no-fund --user-agent apinata-research >/dev/null
mkdir -p dist
for name in buffer ajv; do
  npx --no-install esbuild "src/$name.js" \
    --bundle --format=cjs --platform=neutral --main-fields=main,module \
    --target=es2020 --minify --legal-comments=none --charset=utf8 \
    --outfile="dist/$name.cjs.js"
done

# cheerio's browser condition is its main export without the undici, stream and buffer loaders; the
# entry adds throwing stand-ins for those. Every Node builtin the libraries could reach loads a stub
# that throws, events is the npm package and setImmediate rides on the engine's setTimeout.
stub=./src/node-stub.js
stubs=()
for builtin in stream string_decoder buffer undici fs http https net tls url util zlib crypto; do
  stubs+=("--alias:$builtin=$stub" "--alias:node:$builtin=$stub")
done
for name in cheerio xml2js; do
  npx --no-install esbuild "src/$name.js" \
    --bundle --format=cjs --platform=neutral --main-fields=main,module \
    --conditions=browser "${stubs[@]}" --alias:events=events --alias:timers=./src/timers.js \
    --target=es2020 --minify --legal-comments=none --charset=utf8 \
    --outfile="dist/$name.cjs.js"
  if grep -q undici "dist/$name.cjs.js"; then
    echo "build.sh: undici reached dist/$name.cjs.js" >&2
    exit 1
  fi
done

vendor=../../crates/apinata-core/src/script/vendor
{
  cat <<'EOF'
/*!
 * buffer 5.7.1 (MIT, licenses/buffer-MIT.txt), with base64-js 1.5.1 (MIT,
 * licenses/base64-js-MIT.txt) and ieee754 1.2.1 (BSD-3-Clause, licenses/ieee754-BSD-3-Clause.txt).
 * Bundled with esbuild 0.28.2; generated by tools/script-bundles/build.sh; do not edit.
 */
EOF
  cat dist/buffer.cjs.js
} >"$vendor/buffer-5.7.1.min.js"
{
  cat <<'EOF'
/*!
 * ajv 8.20.0 (MIT, licenses/ajv-MIT.txt) and ajv-formats 2.1.1 (MIT, licenses/ajv-formats-MIT.txt),
 * with fast-deep-equal 3.1.3 (MIT, licenses/fast-deep-equal-MIT.txt), fast-uri 3.1.9
 * (BSD-3-Clause, licenses/fast-uri-BSD-3-Clause.txt) and json-schema-traverse 1.0.0 (MIT,
 * licenses/json-schema-traverse-MIT.txt).
 * Bundled with esbuild 0.28.2; generated by tools/script-bundles/build.sh; do not edit.
 */
EOF
  cat dist/ajv.cjs.js
} >"$vendor/ajv-8.20.0.min.js"
{
  cat <<'EOF2'
/*!
 * cheerio 1.0.0 (MIT, licenses/cheerio-MIT.txt), with parse5 7.3.0 and parse5-htmlparser2-tree-adapter
 * 7.1.0 (MIT, licenses/parse5-MIT.txt), htmlparser2 9.1.0 (MIT, licenses/htmlparser2-MIT.txt),
 * dom-serializer 2.0.0 (MIT, licenses/dom-serializer-MIT.txt), entities 4.5.0 and 6.0.1, domhandler
 * 5.0.3, domutils 3.2.2, domelementtype 2.3.0, css-select 5.2.2, css-what 6.2.2, nth-check 2.1.1 and
 * cheerio-select 2.1.0 (BSD-2-Clause, licenses/<name>-BSD-2-Clause.txt), boolbase 1.0.0 (ISC,
 * licenses/boolbase-ISC.txt).
 * Bundled with esbuild 0.28.2; generated by tools/script-bundles/build.sh; do not edit.
 */
EOF2
  cat dist/cheerio.cjs.js
} >"$vendor/cheerio-1.0.0.min.js"
{
  cat <<'EOF2'
/*!
 * xml2js 0.6.2 (MIT, licenses/xml2js-MIT.txt), with sax 1.4.1 (ISC, licenses/sax-ISC.txt),
 * xmlbuilder 11.0.1 (MIT, licenses/xmlbuilder-MIT.txt) and events 3.3.0 (MIT, licenses/events-MIT.txt).
 * Bundled with esbuild 0.28.2; generated by tools/script-bundles/build.sh; do not edit.
 */
EOF2
  cat dist/xml2js.cjs.js
} >"$vendor/xml2js-0.6.2.min.js"
